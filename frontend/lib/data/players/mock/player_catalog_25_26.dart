PlayerCompetitionStats _competition(
  String code,
  int appearances,
  int wins,
  double rating, {
  String? name,
}) =>
    PlayerCompetitionStats(
      competitionCode: code,
      competitionName: name ?? code,
      appearances: appearances,
      wins: wins,
      rating: rating,
    );

PlayerCareerSeason _careerSeason(
  int teamId,
  String seasonLabel,
  List<PlayerCompetitionStats> competitions,
) =>
    PlayerCareerSeason(
      teamId: teamId,
      seasonLabel: seasonLabel,
      competitions: competitions,
    );

Player _player({
  required String id,
  required String name,
  required String shortName,
  List<String> aliases = const [],
  required int teamId,
  required String team,
  required String league,
  required String leagueCode,
  required int number,
  required List<PlayerPosition> positions,
  required String nationality,
  required String flag,
  required String birthDate,
  required int height,
  required int weight,
  required String foot,
  required int teamColor,
  required String logo,
  String? image,
  required int appearances,
  required int goals,
  required int assists,
  required double rating,
  required double ranking,
  int rankingChange = 0,
  bool favorite = false,
  bool oneToWatch = false,
  required List<double> radar,
  String marketValue = '€50M',
  String form = 'Good',
  String role = 'Important',
  List<PlayerClubPeriod>? history,
  List<PlayerCareerSeason>? careerSeasons,
  List<PlayerAward> personalAwards = const [],
}) {
  final primary = Color(teamColor);
  final isGoalkeeper = positions.contains(PlayerPosition.goalkeeper);
  final starts = appearances > 2 ? appearances - 2 : appearances;
  final passesPerGame = isGoalkeeper
      ? 32
      : positions.contains(PlayerPosition.defender)
          ? 61
          : positions.contains(PlayerPosition.midfielder)
              ? 54
              : 31;

  return Player(
    id: id,
    fullName: name,
    shortName: shortName,
    searchAliases: aliases,
    teamId: teamId,
    teamName: team,
    leagueName: league,
    leagueCode: leagueCode,
    jerseyNumber: number,
    positions: positions,
    nationality: nationality,
    nationalityFlag: flag,
    dateOfBirth: birthDate,
    heightCm: height,
    weightKg: weight,
    preferredFoot: foot,
    marketValue: marketValue,
    form: form,
    squadRole: role,
    teamColor: [primary, primary.withValues(alpha: 0)],
    imageAsset: image,
    teamLogoAsset: logo,
    rankingScore: ranking,
    rankingChange: rankingChange,
    isFavorite: favorite,
    isOneToWatch: oneToWatch,
    radarValues: radar,
    seasonStats: PlayerSeasonStats(
      appearances: appearances,
      starts: starts,
      goals: goals,
      assists: assists,
      rating: rating,
      passes: appearances * passesPerGame,
      passAccuracy: isGoalkeeper
          ? 0.84
          : positions.contains(PlayerPosition.defender)
              ? 0.91
              : positions.contains(PlayerPosition.midfielder)
                  ? 0.89
                  : 0.81,
      cleanSheets: isGoalkeeper ? (appearances * 0.38).round() : 0,
      saves: isGoalkeeper ? appearances * 3 : 0,
    ),
    clubHistory: history ??
        [
          PlayerClubPeriod(
            club: team,
            logoAsset: logo,
            fromSeason: '25/26',
            toSeason: '25/26',
            appearances: appearances,
            goals: goals,
          ),
        ],
    careerSeasons: careerSeasons ??
        [
          _careerSeason(
            teamId,
            '25/26',
            [
              _competition(
                leagueCode,
                appearances,
                (appearances * 0.6).round(),
                rating,
                name: league,
              ),
            ],
          ),
        ],
    personalAwards: personalAwards,
  );
}

